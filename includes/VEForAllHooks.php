	/**
	 * Implements BeforePageDisplay hook.
	 * See https://www.mediawiki.org/wiki/Manual:Hooks/BeforePageDisplay
	 *
	 * @param OutputPage $output OutputPage object
	 * @param Skin $skin Skin object that will be used to generate the page
	 */
	public static function onBeforePageDisplay( $output, $skin ) {
		// Toolbar styles now belong to ext.veforall.main, which Page Forms
		// loads only when an actual VEForAll textarea is on the page.
		// Do not ship VisualEditor dependencies on ordinary read pages.
		// VEForAll.js loads the required core/mobile/desktop modules when
		// an editor is initialized. Flow manages its own VE dependencies.
		$action = $output->getRequest()->getVal( 'action' ) ?: 'view';
		$title = $output->getTitle();
		$isFormEdit = $action === 'formedit' ||
			( $title && $title->isSpecial( 'FormEdit' ) );
		if ( $action === 'view' && !$isFormEdit ) {
			return;
		}

		// Preserve the legacy eager path for other non-Page-Forms actions.
		if ( $output->getConfig()->get( 'VEForAllLazyPageForms' ) && $isFormEdit ) {
			return;
		}
		$services = MediaWikiServices::getInstance();
		if ( !(
			ExtensionRegistry::getInstance()->isLoaded( 'MobileFrontend' ) &&
			$services->getService( 'MobileFrontend.Context' )
				->shouldDisplayMobileView()
		) ) {
			$output->addModules( [
				'ext.veforall.core.desktop'
			] );
		}
	}

	/**
	 * @param array &$vars
	 * @param OutputPage $out
	 *
	 * @throws FatalError
	 * @throws MWException
	 */
	public static function onMakeGlobalVariablesScript( &$vars, $out ) {
		$vars['wgVEForAllLazyPageForms'] = (bool)$out->getConfig()->get( 'VEForAllLazyPageForms' );
		$vars[ 'VEForAllToolbarNormal' ] = self::getVeToolbarConfig( 'normal' );
		$vars[ 'VEForAllToolbarWide' ] = self::getVeToolbarConfig( 'wide' );
	}

	/**
	 * @param string $type
	 *
	 * @return array
	 * @throws FatalError
	 * @throws MWException
	 */
	public static function getVeToolbarConfig( $type = 'normal' ) {
		// Hooks receive a fresh copy: changes for one invocation must not
		// accumulate in the static defaults or leak across subsequent calls.
		$config = self::$defaultConfig[ $type ];
		MediaWikiServices::getInstance()->getHookContainer()
			->run( 'VEForAllToolbarConfig' . ucfirst( $type ), [ &$config ] );
		return array_values( $config );
	}

